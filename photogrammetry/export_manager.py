"""
Standard Deliverables Export Manager (Etapa 7)
==============================================
Exports the 8 standard production deliverables according to the AGENTS.md contract:
  output/
  ├── obj/
  │   ├── high/ (high_model.obj, high_model_texture.png, high_model_normal.png, material.mtl)
  │   └── low/  (low_model.obj, low_model_texture.jpg, low_model_normal.png, material.mtl)
  ├── glb/ (high_model.glb, low_model.glb)
  ├── stl/ (high_model.stl, low_model.stl)
  └── 3mf/ (high_model.3mf, low_model.3mf)
"""

import time
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Any, Optional, Tuple, Union, List

import trimesh

from converters import (
    convert_to_glb_draco,
    convert_to_stl,
    convert_to_3mf,
)

log = logging.getLogger("Photogrammetry.Export")


@dataclass
class ExportResult:
    """Contains paths and telemetry for the 8 standard deliverable files."""
    deliverables: Dict[str, Path]
    total_files_count: int
    execution_time_s: float
    is_complete: bool


class StandardDeliverablesExporter:
    """
    Manages generation of OBJ, GLB (Draco), STL, and 3MF production deliverables.
    """

    def __init__(self, output_dir: Union[str, Path]):
        self.output_dir = Path(output_dir).resolve()

    def export_all_deliverables(
        self,
        high_mesh: trimesh.Trimesh,
        low_mesh: trimesh.Trimesh,
    ) -> ExportResult:
        """
        Exports both High-Poly and Low-Poly models into the 8 standard files.
        """
        t_start = time.time()
        out_d = self.output_dir

        obj_high_dir = out_d / "obj" / "high"
        obj_low_dir = out_d / "obj" / "low"
        glb_dir = out_d / "glb"
        stl_dir = out_d / "stl"
        t3mf_dir = out_d / "3mf"

        for d in [obj_high_dir, obj_low_dir, glb_dir, stl_dir, t3mf_dir]:
            d.mkdir(parents=True, exist_ok=True)

        deliverables: Dict[str, Path] = {}

        log.info("Exporting 8 Standard Production Deliverables into: %s", out_d)

        # 1. OBJ High & Low
        p_obj_high = obj_high_dir / "high_model.obj"
        p_obj_low = obj_low_dir / "low_model.obj"

        high_mesh.export(str(p_obj_high))
        low_mesh.export(str(p_obj_low))
        deliverables["obj_high"] = p_obj_high
        deliverables["obj_low"] = p_obj_low

        # Remove redundant material_0.png auto-generated by Trimesh OBJ exporter
        for mat_png in [obj_high_dir / "material_0.png", obj_low_dir / "material_0.png"]:
            if mat_png.is_file():
                try:
                    mat_png.unlink()
                except Exception:
                    pass

        # Write clean standard material.mtl files linking to the correct textures
        mtl_high = obj_high_dir / "material.mtl"
        with open(mtl_high, "w", encoding="utf-8") as f:
            f.write("""# Standard PBR Material Definition
newmtl material_0
Ka 1.000 1.000 1.000
Kd 1.000 1.000 1.000
Ks 0.050 0.050 0.050
Ns 10.0
d 1.0
illum 2
map_Kd high_model_texture.png
bump high_model_normal.png
norm high_model_normal.png
""")

        mtl_low = obj_low_dir / "material.mtl"
        with open(mtl_low, "w", encoding="utf-8") as f:
            f.write("""# Standard PBR Material Definition
newmtl material_0
Ka 1.000 1.000 1.000
Kd 1.000 1.000 1.000
Ks 0.050 0.050 0.050
Ns 10.0
d 1.0
illum 2
map_Kd low_model_texture.jpg
bump low_model_normal.png
norm low_model_normal.png
""")

        # 2. GLB High & Low (with Draco compression hook)
        p_glb_high = glb_dir / "high_model.glb"
        p_glb_low = glb_dir / "low_model.glb"

        convert_to_glb_draco(high_mesh, p_glb_high)
        convert_to_glb_draco(low_mesh, p_glb_low)
        deliverables["glb_high"] = p_glb_high
        deliverables["glb_low"] = p_glb_low

        # 3. STL High & Low
        p_stl_high = stl_dir / "high_model.stl"
        p_stl_low = stl_dir / "low_model.stl"

        convert_to_stl(high_mesh, p_stl_high)
        convert_to_stl(low_mesh, p_stl_low)
        deliverables["stl_high"] = p_stl_high
        deliverables["stl_low"] = p_stl_low

        # 4. 3MF High & Low
        p_3mf_high = t3mf_dir / "high_model.3mf"
        p_3mf_low = t3mf_dir / "low_model.3mf"

        convert_to_3mf(high_mesh, p_3mf_high)
        convert_to_3mf(low_mesh, p_3mf_low)
        deliverables["3mf_high"] = p_3mf_high
        deliverables["3mf_low"] = p_3mf_low

        # Verify all 8 primary model deliverables exist
        all_exist = all(p.is_file() and p.stat().st_size > 0 for p in deliverables.values())
        dt = time.time() - t_start

        log.info("Exported all 8 deliverables in %.2fs (Status: %s):", dt, "COMPLETE" if all_exist else "INCOMPLETE")
        for key, p in deliverables.items():
            sz_kb = p.stat().st_size / 1024.0 if p.is_file() else 0.0
            log.info("  • %s: %s (%.1f KB)", key, p.name, sz_kb)

        return ExportResult(
            deliverables=deliverables,
            total_files_count=len(deliverables),
            execution_time_s=dt,
            is_complete=all_exist,
        )
